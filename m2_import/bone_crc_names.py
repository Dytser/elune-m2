_SIDES = ("", "L", "R", "Left", "Right", "l", "r")
_SIDE_CANON = {"L": "L", "l": "L", "Left": "L", "R": "R", "r": "R", "Right": "R"}
_NUMS = (("",) + tuple(str(i) for i in range(21))
         + tuple("%02d" % i for i in range(21)) + tuple("%03d" % i for i in range(6)))
_PATTERNS = (
    "{s}{n}", "{s}_{n}", "{s}{sd}{n}", "{s}_{sd}{n}", "{s}{n}_{sd}",
    "{s}_{sd}_{n}", "{sd}_{s}{n}", "{sd}_{s}_{n}", "{s}{n}{sd}", "{s}.{sd}{n}",
    "{s}{sd}_{n}", "{s}_{n}_{sd}", "{sd}{s}{n}",
)


def recover(wanted):
    """Map crc -> name for the CRCs in ``wanted`` that the dictionary hits."""
    wanted = set(wanted)
    found = {}
    if not wanted:
        return found
    crc32 = zlib.crc32
    for s in _STEMS:
        for sd in _SIDES:
            side = _SIDE_CANON.get(sd, "")
            for n in _NUMS:
                # Blender-friendly spelling of whatever matched: UpArmL -> UpArm_L
                canon = s + n + ("_" + side if side else "")
                for pat in _PATTERNS:
                    t = pat.format(s=s, sd=sd, n=n).strip("_.")
                    h = crc32(t.encode())
                    if h in wanted and h not in found:
                        found[h] = canon
    return found
